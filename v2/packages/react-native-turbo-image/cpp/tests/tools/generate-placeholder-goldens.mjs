// Generates cpp/tests/PlaceholderGoldens.inc from the canonical reference
// implementations (npm `blurhash` 2.0.5 by Wolt, npm `thumbhash` 0.1.1 by
// Evan Wallace). The C++ decoders must reproduce these outputs byte for
// byte; that is what makes "one C++ implementation on both platforms" a
// faithful replacement for the two 1.x ports.
//
// Usage (from packages/react-native-turbo-image):
//   bun run goldens:placeholder
//
// Each golden records the decoded size and an FNV-1a 32-bit hash of the
// straight-alpha RGBA bytes, plus a few spot pixels so a mismatch says
// *where* the output diverged, not only that it did.

import { decode as decodeBlurhash, encode as encodeBlurhash } from 'blurhash';
import { rgbaToThumbHash, thumbHashToRGBA } from 'thumbhash';

function fnv1a(bytes) {
  let hash = 0x811c9dc5;
  for (const b of bytes) {
    hash ^= b;
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

// Deterministic synthetic images so the inputs are reproducible without
// shipping binary fixtures: a two-axis colour gradient, optionally with an
// alpha ramp.
function syntheticRgba(w, h, withAlpha) {
  const out = new Uint8ClampedArray(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const i = (y * w + x) * 4;
      out[i] = Math.round((255 * x) / (w - 1));
      out[i + 1] = Math.round((255 * y) / (h - 1));
      out[i + 2] = Math.round((255 * ((x + y) % 7)) / 6);
      out[i + 3] = withAlpha ? Math.round((255 * (x + y)) / (w + h - 2)) : 255;
    }
  }
  return out;
}

function spots(rgba, w, h) {
  const at = (x, y) => Array.from(rgba.slice((y * w + x) * 4, (y * w + x) * 4 + 4));
  return [
    [0, 0, ...at(0, 0)],
    [w - 1, h - 1, ...at(w - 1, h - 1)],
    [w >> 1, h >> 1, ...at(w >> 1, h >> 1)],
  ];
}

const lines = [
  '// GENERATED by cpp/tests/tools/generate-placeholder-goldens.mjs. Do not edit.',
  '// Reference implementations: blurhash 2.0.5, thumbhash 0.1.1.',
  '',
];

// Double braces: the outer pair initialises std::array, the inner pair its
// underlying C array (otherwise the first Spot's fields would be consumed).
const emitSpots = (s) =>
  `{{${s.map(([x, y, r, g, b, a]) => `{${x}, ${y}, {${r}, ${g}, ${b}, ${a}}}`).join(', ')}}}`;

// --- blurhash ---------------------------------------------------------------
const blurhashCases = [
  // The canonical example from the blurhash README.
  { name: 'readme', hash: 'LEHV6nWB2yk8pyo0adR*.7kCMdnj', w: 32, h: 32 },
  // Non-square output and a non-square component grid.
  { name: 'readme_wide', hash: 'LEHV6nWB2yk8pyo0adR*.7kCMdnj', w: 40, h: 24 },
  // Encoded here from the synthetic image: 1x1 (DC only) and 9x9 (maximum).
  { name: 'dc_only', hash: encodeBlurhash(syntheticRgba(16, 16, false), 16, 16, 1, 1), w: 8, h: 8 },
  {
    name: 'max_components',
    hash: encodeBlurhash(syntheticRgba(32, 32, false), 32, 32, 9, 9),
    w: 32,
    h: 32,
  },
];
lines.push('inline const BlurhashGolden kBlurhashGoldens[] = {');
for (const c of blurhashCases) {
  const rgba = decodeBlurhash(c.hash, c.w, c.h);
  lines.push(
    `    {"${c.name}", R"(${c.hash})", ${c.w}, ${c.h}, 0x${fnv1a(rgba).toString(16).padStart(8, '0')}u, ${emitSpots(spots(rgba, c.w, c.h))}},`
  );
}
lines.push('};', '');

// --- thumbhash --------------------------------------------------------------
const thumbhashCases = [
  { name: 'landscape_opaque', w: 64, h: 40, alpha: false },
  { name: 'portrait_opaque', w: 40, h: 64, alpha: false },
  { name: 'landscape_alpha', w: 64, h: 40, alpha: true },
  { name: 'square_alpha', w: 48, h: 48, alpha: true },
];
lines.push('inline const ThumbhashGolden kThumbhashGoldens[] = {');
for (const c of thumbhashCases) {
  const hash = rgbaToThumbHash(c.w, c.h, syntheticRgba(c.w, c.h, c.alpha));
  const base64 = Buffer.from(hash).toString('base64');
  const { w, h, rgba } = thumbHashToRGBA(hash);
  lines.push(
    `    {"${c.name}", "${base64}", ${w}, ${h}, 0x${fnv1a(rgba).toString(16).padStart(8, '0')}u, ${emitSpots(spots(rgba, w, h))}},`
  );
}
lines.push('};');

console.log(lines.join('\n'));
